/**
 * Record a cap-table distribution. When the portfolio company came
 * through a deal (monitoring getPortfolioCompany → dealId) AND a
 * personId is given, the distribution is ALSO written to Investors &
 * Capital via lib/capital/reporting.ts createReportEntry — its exact
 * signature is createReportEntry(dealId, { investorPersonId,
 * entryType: 'distribution', amount, asOf, notes }, actor) — and the
 * returned entry id is stored as capital_entry_id so the two ledgers
 * can be reconciled (see getCapTable's capitalTotals).
 */
export async function recordDistribution(
  companyId: string,
  input: {
    holderId?: string | null;
    personId?: string | null;
    amount: number;
    paidOn?: string | null;
    notes?: string;
  },
  actor: string
): Promise<CapDistributionRow> {
  await ensurePortmgmt();
  const amount = validMoney(input.amount);
  if (amount < 0) throw new PortmgmtError("invalid_amount");
  const paidOn =
    input.paidOn === undefined || input.paidOn === null
      ? phoenixToday()
      : requireDate(input.paidOn, "invalid_date");
  const personId = input.personId ?? null;

  let capitalEntryId: string | null = null;
  const pc = await getPortfolioCompany(companyId).catch(() => null);
  if (pc?.dealId && personId) {
    const entry = await createReportEntry(
      pc.dealId,
      {
        investorPersonId: personId,
        entryType: "distribution",
        amount,
        asOf: paidOn,
        notes: input.notes ?? "",
        source: "cap_table",
      },
      actor
    );
    capitalEntryId = entry.id;
  }

  const db = sql();
  const id = `pmdist_${newId()}`;
  await db`
    INSERT INTO portmgmt.cap_distributions
      (id, company_id, holder_id, person_id, amount, paid_on, notes,
       capital_entry_id, created_by)
    VALUES (${id}, ${companyId}, ${input.holderId ?? null}, ${personId},
      ${amount}, ${paidOn}, ${input.notes ?? ""}, ${capitalEntryId},
      ${actor})`;
  const rows = await db`
    SELECT * FROM portmgmt.cap_distributions WHERE id = ${id} LIMIT 1`;
  return rowToDistribution(rows[0] as Record<string, unknown>);
}

