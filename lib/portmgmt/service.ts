const MEETING_STATUSES = ["scheduled", "held", "cancelled"] as const;

export interface MeetingInput {
  title?: string;
  startsAt?: string | null;
  endsAt?: string | null;
  status?: string;
  agenda?: string;
  minutes?: string;
  decisions?: string;
  attendees?: unknown[];
}

export async function createMeeting(
  companyId: string,
  input: MeetingInput,
  actor: string
): Promise<BoardMeetingRow> {
  await ensurePortmgmt();
  const title = (input.title ?? "").trim();
  if (!title) throw new PortmgmtError("title_required");
  const status = (input.status ?? "scheduled").trim() || "scheduled";
  if (!(MEETING_STATUSES as readonly string[]).includes(status)) {
    throw new PortmgmtError("invalid_status");
  }
  const db = sql();
  const id = `pmmeet_${newId()}`;
  await db`
    INSERT INTO portmgmt.board_meetings
      (id, company_id, title, starts_at, ends_at, status, agenda,
       minutes, decisions, attendees, created_by)
    VALUES (${id}, ${companyId}, ${title},
      ${input.startsAt ?? null}::timestamptz,
      ${input.endsAt ?? null}::timestamptz, ${status},
      ${input.agenda ?? ""}, ${input.minutes ?? ""},
      ${input.decisions ?? ""},
      ${JSON.stringify(input.attendees ?? [])}::jsonb, ${actor})`;
  const meeting = await getMeeting(companyId, id);
  if (!meeting) throw new PortmgmtError("meeting_not_found");
  return meeting;
}

