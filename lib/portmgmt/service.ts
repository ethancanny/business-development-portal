/**
 * Generate a compliance certificate PDF from the LATEST stored
 * covenant test per covenant (monitoring getCovenants' `tests` list).
 * Figures are cited from the stored tests verbatim — never recomputed
 * here — and the same snapshot is stored on the certificate row.
 */
export async function generateCertificate(
  companyId: string,
  input: { periodEnd?: string } = {},
  actor = ""
): Promise<LenderCertificateRow> {
  await ensurePortmgmt();
  const { tests } = await getCovenants(companyId);
  const periodEnd = input.periodEnd
    ? requireDate(input.periodEnd, "invalid_period_end")
    : (tests
        .map((t) => t.periodEnd)
        .filter((d): d is string => Boolean(d))
        .sort()
        .pop() ?? null);
  const snapshot = tests.map((t) => ({
    covenantId: t.covenantId,
    covenantKey: t.covenantKey,
    label: t.label,
    computedValue: t.computedValue,
    threshold: t.threshold,
    headroomPct: t.headroomPct,
    status: t.status,
    periodEnd: t.periodEnd,
  }));
  const rows: string[][] = [
    ["Covenant", "Computed", "Threshold", "Headroom", "Status", "Period"],
    ...snapshot.map((t) => [
      t.label || t.covenantKey,
      t.computedValue === null ? "—" : String(t.computedValue),
      t.threshold === null ? "—" : String(t.threshold),
      t.headroomPct === null ? "—" : `${t.headroomPct}%`,
      t.status,
      t.periodEnd ?? "—",
    ]),
  ];
  if (!snapshot.length) {
    rows.push(["No covenant tests on record", "", "", "", "", ""]);
  }
  const bytes = buildSimplePdf({
    title: "Compliance Certificate",
    subtitle: `Period ending ${periodEnd ?? "—"} · Figures as tested and stored in Portfolio Monitoring (not recomputed)`,
    sections: [{ heading: "Covenant tests — latest per covenant", rows }],
  });
  const slug = periodEnd ?? "latest";
  const { documentId } = await storeBytesAsDocument({
    bytes,
    filename: `compliance-certificate-${slug}.pdf`,
    mime: "application/pdf",
    companyId,
    tags: ["compliance_certificate"],
    actor,
  });
  const db = sql();
  const id = `pmcert_${newId()}`;
  await db`
    INSERT INTO portmgmt.lender_certificates
      (id, company_id, period_end, document_id, tests_snapshot, created_by)
    VALUES (${id}, ${companyId}, ${periodEnd}, ${documentId},
      ${JSON.stringify(snapshot)}::jsonb, ${actor})`;
  const certRows = await db`
    SELECT * FROM portmgmt.lender_certificates WHERE id = ${id} LIMIT 1`;
  return rowToCertificate(certRows[0] as Record<string, unknown>);
}

export const DEFAULT_ADVANCE_RATE = 0.8;

/**
 * Compute a borrowing-base snapshot from the latest AR aging snapshot
 * (monitoring analytics getAging).
 *
 * ELIGIBILITY RULE: eligible AR = total AR − the over-90-day bucket
 * (d90_plus), using the aging buckets exactly as stored. Borrowing
 * base = eligible AR × advance rate (default 0.80). Availability =
 * max(0, min(base, revolver limit) − revolver drawn) from the latest
 * cash position (monitoring getCash); with no revolver on record the
 * base is still computed but availability stays null with the reason
 * recorded. With no AR aging snapshot at all, the snapshot row is
 * stored with not_applicable_reason 'no_ar_aging_snapshot'.
 */
export async function computeBorrowingBase(
  companyId: string,
  input: { advanceRate?: number } = {},
  actor = ""
): Promise<BorrowingBaseRow> {
  await ensurePortmgmt();
  const advanceRate =
    input.advanceRate !== undefined
      ? validMoney(input.advanceRate, "invalid_advance_rate")
      : DEFAULT_ADVANCE_RATE;
  if (advanceRate < 0 || advanceRate > 1) {
    throw new PortmgmtError("invalid_advance_rate");
  }
  const aging = await getAging(companyId);
  const cash = await getCash(companyId);
  const db = sql();
  const id = `pmbb_${newId()}`;
  const asOf = aging.ar?.asOf ?? cash.asOf ?? phoenixToday();

  if (!aging.ar) {
    await db`
      INSERT INTO portmgmt.borrowing_base_snapshots
        (id, company_id, as_of, advance_rate, not_applicable_reason,
         created_by)
      VALUES (${id}, ${companyId}, ${asOf}, ${advanceRate},
        'no_ar_aging_snapshot', ${actor})`;
  } else {
    const totalAr = aging.ar.total;
    const over90 = aging.ar.d90Plus ?? 0;
    const eligible =
      totalAr === null ? null : round2(Math.max(0, totalAr - over90));
    const base =
      eligible === null ? null : round2(eligible * advanceRate);
    const limit = cash.revolverLimit;
    const drawn = cash.revolverDrawn;
    let availability: number | null = null;
    let reason = "";
    if (limit === null || drawn === null || base === null) {
      reason = "no_revolver";
    } else {
      availability = round2(Math.max(0, Math.min(base, limit) - drawn));
    }
    await db`
      INSERT INTO portmgmt.borrowing_base_snapshots
        (id, company_id, as_of, total_ar, over90_amount, eligible_ar,
         advance_rate, borrowing_base, revolver_limit, revolver_drawn,
         availability, not_applicable_reason, created_by)
      VALUES (${id}, ${companyId}, ${asOf}, ${totalAr}, ${over90},
        ${eligible}, ${advanceRate}, ${base}, ${limit}, ${drawn},
        ${availability}, ${reason}, ${actor})`;
  }
  const rows = await db`
    SELECT * FROM portmgmt.borrowing_base_snapshots WHERE id = ${id} LIMIT 1`;
  return rowToBorrowingBase(rows[0] as Record<string, unknown>);
}

