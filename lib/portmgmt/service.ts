const EW_WEIGHTS = {
  timeliness: 0.3,
  kpiMisses: 0.25,
  covenant: 0.25,
  cashTrend: 0.2,
} as const;

function bandFor(score: number | null): string {
  if (score === null) return "unknown";
  if (score < 25) return "low";
  if (score < 50) return "watch";
  if (score < 75) return "elevated";
  return "critical";
}

function rowToEarlyWarning(
  r: Record<string, unknown>,
  companyName = ""
): EarlyWarningRow {
  const components = jsonObj(r.components) as unknown as Partial<EarlyWarningComponents>;
  const score = numOrNull(r.score);
  return {
    companyId: str(r.company_id),
    companyName,
    score,
    band: str(r.band) || bandFor(score),
    components: {
      timeliness: components.timeliness ?? null,
      kpiMisses: components.kpiMisses ?? null,
      covenant: components.covenant ?? null,
      cashTrend: components.cashTrend ?? null,
    },
    computedAt: isoOrNull(r.computed_at),
  };
}

/**
 * Compute the early-warning score for one company from monitoring
 * reads ONLY (through monitoring's service/analytics functions):
 * - timeliness (.30): latest reporting period — none → null; status
 *   'late', or pending past its due date → 90; received → 10;
 *   pending and not yet due → 20.
 * - kpiMisses (.25): open kpi_miss alerts → min(100, 40 × count).
 * - covenant (.25): latest test per covenant — any fail → 100; else
 *   by minimum headroom h (% points): h ≥ 50 → 0, ≥ 25 → 30,
 *   ≥ 10 → 60, else 85; no tests → null.
 * - cashTrend (.20): last two cash KPI values (newest vs prior) —
 *   decline > 20% → 70, > 5% → 40, otherwise 5; < 2 points → null.
 * Score = weighted mean renormalized over the non-null components;
 * no components → score null, band 'unknown'. The result is upserted
 * into portmgmt.early_warning_scores (the stored read model).
 */
export async function computeEarlyWarning(
  companyId: string
): Promise<EarlyWarningRow> {
  await ensurePortmgmt();
  const summary = await getMonitoringSummaryForCompany(companyId);

  // Timeliness — from the company's reporting periods.
  let timeliness: number | null = null;
  const periods = await listPeriods(companyId).catch(() => []);
  const latestPeriod = periods.length ? periods[0] : null;
  if (latestPeriod) {
    if (latestPeriod.status === "received") timeliness = 10;
    else if (latestPeriod.status === "late") timeliness = 90;
    else if (
      latestPeriod.dueDate &&
      latestPeriod.dueDate < phoenixToday()
    ) {
      timeliness = 90; // overdue and unreceived
    } else timeliness = 20;
  } else if (summary) {
    timeliness = null;
  }

  // KPI misses — open kpi_miss alerts only.
  let kpiMisses: number | null = null;
  try {
    const open = await listAlerts(companyId, "open");
    const count = open.filter((a) => a.ruleKey === "kpi_miss").length;
    kpiMisses = Math.min(100, 40 * count);
  } catch {
    // Fall back to the analytics list (same underlying store).
    const { items } = await listCompanyAlerts(companyId, {
      status: "open",
      limit: 100,
    });
    const count = (items as Array<Record<string, unknown>>).filter(
      (a) => a.ruleKey === "kpi_miss" || a.rule_key === "kpi_miss"
    ).length;
    kpiMisses = Math.min(100, 40 * count);
  }

  // Covenant — latest test per covenant (getCovenants' tests list).
  let covenant: number | null = null;
  const { tests } = await getCovenants(companyId);
  if (tests.length) {
    if (tests.some((t) => t.status === "fail")) covenant = 100;
    else {
      const headrooms = tests
        .map((t) => t.headroomPct)
        .filter((h): h is number => h !== null);
      if (headrooms.length) {
        const h = Math.min(...headrooms);
        covenant = h >= 50 ? 0 : h >= 25 ? 30 : h >= 10 ? 60 : 85;
      } else {
        covenant = 0; // tests exist and all pass, headroom unreported
      }
    }
  }

  // Cash trend — last two cash values from KPI history.
  let cashTrend: number | null = null;
  const kpis = await getKpis(companyId).catch(() => null);
  if (kpis) {
    const cashValues = kpis.periods
      .map((p) => p.cash)
      .filter((v): v is number => v !== null);
    if (cashValues.length >= 2) {
      const [latest, prior] = cashValues;
      if (prior !== 0) {
        const decline = ((prior - latest) / Math.abs(prior)) * 100;
        cashTrend = decline > 20 ? 70 : decline > 5 ? 40 : 5;
      } else {
        cashTrend = latest < 0 ? 70 : 5;
      }
    }
  }

  const components: EarlyWarningComponents = {
    timeliness,
    kpiMisses,
    covenant,
    cashTrend,
  };
  let weighted = 0;
  let weightSum = 0;
  (Object.keys(EW_WEIGHTS) as Array<keyof typeof EW_WEIGHTS>).forEach(
    (key) => {
      const v = components[key];
      if (v !== null) {
        weighted += v * EW_WEIGHTS[key];
        weightSum += EW_WEIGHTS[key];
      }
    }
  );
  const score = weightSum > 0 ? round2(weighted / weightSum) : null;
  const band = bandFor(score);

  const db = sql();
  await db`
    INSERT INTO portmgmt.early_warning_scores
      (company_id, score, band, components, computed_at, updated_at)
    VALUES (${companyId}, ${score}, ${band},
      ${JSON.stringify(components)}::jsonb, now(), now())
    ON CONFLICT (company_id) DO UPDATE SET
      score = EXCLUDED.score, band = EXCLUDED.band,
      components = EXCLUDED.components, computed_at = now(),
      updated_at = now()`;
  const rows = await db`
    SELECT * FROM portmgmt.early_warning_scores
    WHERE company_id = ${companyId} LIMIT 1`;
  return rowToEarlyWarning(rows[0] as Record<string, unknown>);
}

/** Safe wrapper for event handlers / background paths: never throws. */
export async function refreshEarlyWarningFor(
  companyId: string
): Promise<void> {
  try {
    await computeEarlyWarning(companyId);
  } catch (err) {
    console.error(
      "[portmgmt] early-warning refresh failed for company",
      companyId,
      err instanceof Error ? err.message : String(err)
    );
  }
}

export async function getEarlyWarning(
  companyId: string
): Promise<EarlyWarningRow> {
  await ensurePortmgmt();
  const db = sql();
  const rows = await db`
    SELECT * FROM portmgmt.early_warning_scores
    WHERE company_id = ${companyId} LIMIT 1`;
  if (rows.length) {
    return rowToEarlyWarning(rows[0] as Record<string, unknown>);
  }
  return computeEarlyWarning(companyId);
}

/**
 * Overview read model: stored early-warning rows for every live
 * portfolio company (names via monitoring listPortfolioCompanies).
 * Companies lacking a stored row are computed on miss — once; the
 * stored row serves every later read.
 */
export async function getEarlyWarningOverview(): Promise<EarlyWarningRow[]> {
  await ensurePortmgmt();
  const companies = await listPortfolioCompanies();
  const db = sql();
  const rows = await db`
    SELECT * FROM portmgmt.early_warning_scores`;
  const stored = new Map<string, Record<string, unknown>>();
  for (const r of rows) {
    const rec = r as Record<string, unknown>;
    stored.set(str(rec.company_id), rec);
  }
  const out: EarlyWarningRow[] = [];
  for (const c of companies) {
    const rec = stored.get(c.companyId);
    if (rec) {
      out.push(rowToEarlyWarning(rec, c.companyName));
    } else {
      const computed = await computeEarlyWarning(c.companyId).catch(
        () => null
      );
      out.push(
        computed
          ? { ...computed, companyName: c.companyName }
          : {
              companyId: c.companyId,
              companyName: c.companyName,
              score: null,
              band: "unknown",
              components: {
                timeliness: null,
                kpiMisses: null,
                covenant: null,
                cashTrend: null,
              },
              computedAt: null,
            }
      );
    }
  }
  return out.sort((a, b) => (b.score ?? -1) - (a.score ?? -1));
}

/* ------------------------- event registration ------------------------ */
/**
 * Early-warning refreshes are event-driven (PROJECT_RULES.md: never
 * poll): reporting_received / covenant_breached / financials_posted
 * refresh the affected company; deal_closed refreshes once the
 * handoff has created the portfolio company (compute-on-miss in the
 * overview covers any ordering gap). Registration is idempotent and
 * side-effect-light at import, mirroring lib/monitoring/service.ts.
 */
let portmgmtHandlersRegistered = false;
function registerPortmgmtHandlers(): void {
  if (portmgmtHandlersRegistered) return;
  portmgmtHandlersRegistered = true;
  const companyIdOf = (evt: {
    entityId: string;
    payload: Record<string, unknown>;
  }): string => {
    const fromPayload =
      typeof evt.payload?.companyId === "string" ? evt.payload.companyId : "";
    return fromPayload || evt.entityId || "";
  };
  onEvent("reporting_received", async (evt) => {
    const companyId = companyIdOf(evt);
    if (companyId) await refreshEarlyWarningFor(companyId);
  });
  onEvent("covenant_breached", async (evt) => {
    const companyId = companyIdOf(evt);
    if (companyId) await refreshEarlyWarningFor(companyId);
  });
  onEvent("financials_posted", async (evt) => {
    const companyId = companyIdOf(evt);
    if (companyId) await refreshEarlyWarningFor(companyId);
  });
  onEvent("deal_closed", async (evt) => {
    const companyId =
      typeof evt.payload?.companyId === "string" ? evt.payload.companyId : "";
    if (companyId) await refreshEarlyWarningFor(companyId);
  });
}
registerPortmgmtHandlers();
