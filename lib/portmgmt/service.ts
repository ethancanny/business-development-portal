/**
 * Rebuild the stored risk summary (portmgmt.risk_summary, id 'global')
 * from LIVE risks — open risks only. Called inside every risk
 * mutation so the Overview never recomputes it on read.
 */
export async function refreshRiskSummary(): Promise<RiskSummaryPayload> {
  await ensurePortmgmt();
  const db = sql();
  const rows = await db`
    SELECT company_id, severity, category FROM portmgmt.risks
    WHERE deleted_at IS NULL AND status = 'open'`;
  const bySeverity: Record<string, number> = {};
  const byCategory: Record<string, number> = {};
  const perCompany = new Map<string, number>();
  for (const r of rows) {
    const rec = r as Record<string, unknown>;
    const sev = str(rec.severity) || "medium";
    const cat = str(rec.category) || "general";
    bySeverity[sev] = (bySeverity[sev] ?? 0) + 1;
    byCategory[cat] = (byCategory[cat] ?? 0) + 1;
    const cid = str(rec.company_id);
    perCompany.set(cid, (perCompany.get(cid) ?? 0) + 1);
  }
  const payload: RiskSummaryPayload = {
    bySeverity,
    byCategory,
    openByCompany: Array.from(perCompany.entries())
      .map(([companyId, open]) => ({ companyId, open }))
      .sort((a, b) => b.open - a.open),
    totalOpen: rows.length,
    computedAt: new Date().toISOString(),
  };
  await db`
    INSERT INTO portmgmt.risk_summary (id, payload, updated_at)
    VALUES ('global', ${JSON.stringify(payload)}::jsonb, now())
    ON CONFLICT (id) DO UPDATE SET
      payload = EXCLUDED.payload, updated_at = now()`;
  return payload;
}

