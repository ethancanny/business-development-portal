/* ------------------------------ helpers ------------------------------ */

function jsonObj(v: unknown): Record<string, unknown> {
  if (v && typeof v === "object" && !Array.isArray(v))
    return v as Record<string, unknown>;
  if (typeof v === "string" && v.trim()) {
    try {
      const p = JSON.parse(v);
      return p && typeof p === "object" && !Array.isArray(p) ? p : {};
    } catch {
      return {};
    }
  }
  return {};
}
function jsonArr<T>(v: unknown): T[] {
  if (Array.isArray(v)) return v as T[];
  if (typeof v === "string" && v.trim()) {
    try {
      const p = JSON.parse(v);
      return Array.isArray(p) ? (p as T[]) : [];
    } catch {
      return [];
    }
  }
  return [];
}
function dateOrNull(v: unknown): string | null {
  if (v == null) return null;
  if (v instanceof Date) return v.toISOString().slice(0, 10);
  const s = String(v);
  return s ? s.slice(0, 10) : null;
}
function cleanDate(v: unknown): string | null {
  if (typeof v !== "string") return null;
  const s = v.trim();
  return /^\d{4}-\d{2}-\d{2}$/.test(s) ? s : null;
}
function requireDate(v: unknown, code = "invalid_date"): string {
  const d = cleanDate(v);
  if (!d) throw new PortmgmtError(code);
  return d;
}
function validMoney(v: unknown, code = "invalid_amount"): number {
  if (typeof v !== "number" || !isFinite(v)) throw new PortmgmtError(code);
  return v;
}
function round2(n: number): number {
  return Math.round(n * 100) / 100;
}
function phoenixToday(): string {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "America/Phoenix",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(new Date());
}
function fmtMoney(v: number | null): string {
  if (v === null || !isFinite(v)) return "—";
  const r = Math.round(v);
  const s = Math.abs(r).toLocaleString("en-US", { maximumFractionDigits: 0 });
  return r < 0 ? `-$${s}` : `$${s}`;
}

/**
 * Store generated bytes as a registered library document: bytes go
 * to the storage provider under an upload temp key and
 * registerUploadedDocument moves them to the canonical version key,
 * creates the core.documents row, and publishes document_uploaded.
 */
export async function storeBytesAsDocument(input: {
  bytes: Buffer;
  filename: string;
  mime: string;
  companyId: string;
  tags: string[];
  actor: string;
}): Promise<{ documentId: string }> {
  const provider = getStorageProvider();
  const tempKey = `uploads/portmgmt-${newId()}.part`;
  await provider.put(tempKey, input.bytes);
  const { document } = await registerUploadedDocument({
    storageKey: tempKey,
    filename: input.filename,
    mime: input.mime,
    sizeBytes: input.bytes.length,
    contentHash: sha256Hex(input.bytes),
    actor: input.actor,
    companyId: input.companyId,
    tags: input.tags,
  });
  return { documentId: document.id };
}

